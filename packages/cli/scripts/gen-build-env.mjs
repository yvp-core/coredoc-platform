#!/usr/bin/env node
/**
 * Codegen for `packages/cli/src/build-env.ts` — see that file's header.
 *
 * Runs as the FIRST step of `pnpm --filter @coredoc/cli build`. The CLI build is
 * pure `tsc` (no bundler `define`), so unlike the desktop app there is no
 * compile-time constant-injection mechanism. Instead this script OVERWRITES
 * `build-env.ts` with the literal, trimmed values of `COREDOC_POSTHOG_KEY` /
 * `COREDOC_POSTHOG_HOST` read from the environment (empty when unset).
 *
 *   - Release CI (env set): the compiled `dist` embeds the real anon key/host.
 *   - Locally / tests (env unset): it rewrites the committed EMPTY defaults
 *     byte-for-byte, so there is no git churn and telemetry stays a no-op.
 *
 * Mirrors the SEMANTICS of `apps/desktop/src/main/build-env.ts` (trimmed
 * strings, runtime env still wins downstream), not its electron-vite mechanism.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));

// Populate `process.env` from the monorepo-root `.env` for any var the shell
// did NOT already set, so the single root `.env` is the one place to configure
// COREDOC_POSTHOG_KEY/HOST. Shell/CI env still wins; a missing `.env` is a no-op.
//
// The loader lives at the monorepo root (`scripts/load-root-env.mjs`), present
// only in a full checkout. In a hermetic/isolated build — the server & CLI
// Docker images copy just `packages/*` (not root `scripts/`), and the published
// npm tarball ships only `dist` — that path is absent. There is also no root
// `.env` in those contexts (never copied into the image, by design), so root-env
// loading is a no-op there anyway: skip silently and let real env vars passed by
// CI win. Any error other than "module not found" still throws (fail-fast).
try {
  const { loadRootEnv } = await import('../../../scripts/load-root-env.mjs');
  loadRootEnv(scriptDir);
} catch (err) {
  if (err?.code !== 'ERR_MODULE_NOT_FOUND') throw err;
}

/** Trim to a string, exactly like the desktop `normalize()`; undefined/blank → ''. */
function normalize(value) {
  return typeof value === 'string' ? value.trim() : '';
}

/** Emit a Biome-clean single-quoted TS string literal (escapes backslashes + quotes). */
function literal(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

const key = normalize(process.env.COREDOC_POSTHOG_KEY);
const host = normalize(process.env.COREDOC_POSTHOG_HOST);

const content = `/**
 * Build-time PostHog anon-channel defaults baked into the standalone CLI dist.
 *
 * GENERATED by \`scripts/gen-build-env.mjs\` as the first step of \`build\`. The
 * committed copy holds EMPTY defaults so that:
 *   - \`import { BUNDLED_POSTHOG_KEY } from './build-env.js'\` ALWAYS resolves,
 *     even with no build step run (dev, tests) — empty ⇒ no-op telemetry,
 *     matching today's behavior;
 *   - locally (env unset) the codegen rewrites these SAME empty values, so
 *     editing this file by hand is pointless and there is no git churn.
 *
 * Do NOT hand-edit — change \`scripts/gen-build-env.mjs\` instead. Mirrors the
 * SEMANTICS of \`apps/desktop/src/main/build-env.ts\`, not its vite \`define\`.
 */

export const BUNDLED_POSTHOG_KEY = ${literal(key)};
export const BUNDLED_POSTHOG_HOST = ${literal(host)};
`;

const target = join(scriptDir, '..', 'src', 'build-env.ts');
writeFileSync(target, content, 'utf-8');
