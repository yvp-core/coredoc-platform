#!/usr/bin/env node
/**
 * Codegen for the CLI and MCP `src/build-env.ts`.
 *
 *   node ../../scripts/gen-build-env.mjs <output file>
 *
 * Runs as the FIRST step of `pnpm --filter @coredoc/{cli,mcp} build`. Those builds
 * are pure `tsc` (no bundler `define`), so this script OVERWRITES the output with
 * the literal, trimmed values of `COREDOC_POSTHOG_KEY` / `COREDOC_POSTHOG_HOST`
 * (empty when unset). Release CI embeds the real anon key/host; locally the
 * values stay empty and telemetry is a no-op.
 *
 * Mirrors the SEMANTICS of `apps/desktop/src/main/build-env.ts` (trimmed
 * strings, runtime env still wins downstream), not its electron-vite mechanism.
 */

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const target = process.argv[2];
if (!target) {
  console.error('usage: gen-build-env.mjs <output file>');
  process.exit(2);
}

// Shell/CI env wins over the root `.env`; there is no root `.env` in Docker builds.
try {
  process.loadEnvFile(new URL('../.env', import.meta.url));
} catch (err) {
  if (err?.code !== 'ENOENT') throw err;
}

/** Trim to a string, exactly like the desktop `normalize()`; undefined/blank → ''. */
function normalize(value) {
  return typeof value === 'string' ? value.trim() : '';
}

/** Emit a Biome-clean single-quoted TS string literal (escapes backslashes + quotes). */
function literal(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

const key = normalize(process.env.COREDOC_POSTHOG_KEY);
const host = normalize(process.env.COREDOC_POSTHOG_HOST);

const content = `/**
 * Build-time PostHog anon-channel defaults baked into this package's dist.
 *
 * GENERATED by \`scripts/gen-build-env.mjs\` (repo root) as the first step of
 * \`build\` and on install; gitignored. Empty values mean no-op telemetry.
 * Do NOT hand-edit.
 */

export const BUNDLED_POSTHOG_KEY = ${literal(key)};
export const BUNDLED_POSTHOG_HOST = ${literal(host)};
`;

writeFileSync(resolve(target), content, 'utf-8');
